function publicErrorMessage(error) {
  // An unexpected getter/toString must not execute while reporting an error.
  let descriptor;
  try {
    descriptor = Object.getOwnPropertyDescriptor(error, "message");
  } catch {
    return GENERIC_ERROR;
  }
  const text = descriptor?.value;
  return typeof text === "string" && PUBLIC_MESSAGES.has(text)
    ? text
    : GENERIC_ERROR;
}
